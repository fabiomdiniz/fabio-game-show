#!/usr/bin/env bash
# Multi-agent worktree harness for fabio-game-show.
#
# Each agent gets its own git worktree, branch, dev-server port and a generated
# .hermes.md that scopes it to a set of paths. Run from anywhere inside the repo.
#
#   scripts/agents.sh setup [agent...]      create/refresh worktrees + agent files
#   scripts/agents.sh dev <agent>           run that agent's Vite server on its port
#   scripts/agents.sh status                branch / dirty files / server per agent
#   scripts/agents.sh urls                  print the URLs (with liveness check)
#   scripts/agents.sh run <agent> [prompt]  open Hermes inside the agent's worktree
#   scripts/agents.sh sync [agent...]       merge main into each agent branch
#   scripts/agents.sh remove <agent> [--delete-branch]
#   scripts/agents.sh list                  show the manifest
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
REPO_ROOT="$PWD"
AGENTS_DIR="${AGENTS_DIR:-$(dirname "$REPO_ROOT")/fabio-game-show-agents}"
BASE_PORT="${BASE_PORT:-5180}"

# Manifest: name | port offset | owned paths | everything else is off-limits
AGENTS=(master board-game fighting jeopardy feud)
owns() {
  case "$1" in
    master)
      cat <<'EOF'
src/screens/**, src/components/**, src/store/**, src/App.tsx, src/main.tsx,
src/types.ts, src/games/register.ts, src/index.css, src/content/**, index.html,
theme/**, docs/**, scripts/**, package.json, vite.config.ts, tsconfig.json
EOF
      ;;
    *) echo "src/games/$1/**" ;;
  esac
}

port_of() {
  local i=0
  for a in "${AGENTS[@]}"; do
    if [ "$a" = "$1" ]; then echo $((BASE_PORT + i)); return 0; fi
    i=$((i + 1))
  done
  return 1
}

worktree_of() { echo "$AGENTS_DIR/$1"; }
branch_of() { echo "agent/$1"; }
app_url() { echo "http://localhost:$(port_of "$1")/"; }

require_agent() {
  if ! port_of "$1" >/dev/null; then
    echo "unknown agent: $1 (known: ${AGENTS[*]})" >&2
    exit 1
  fi
}

ensure_exclude() {
  local ex
  ex="$(git rev-parse --git-common-dir)/info/exclude"
  mkdir -p "$(dirname "$ex")"
  grep -qx '.hermes.md' "$ex" 2>/dev/null || printf '\n# multi-agent worktrees (scripts/agents.sh)\n.hermes.md\n.agent/\n' >>"$ex"
}

write_agent_files() {
  local name="$1" wt="$2" port url
  port="$(port_of "$name")"
  url="$(app_url "$name")"
  mkdir -p "$wt/.agent"

  cat >"$wt/.agent/env" <<EOF
AGENT=$name
PORT=$port
URL=$url
BRANCH=$(branch_of "$name")
EOF

  cat >"$wt/.agent/dev.sh" <<'EOF'
#!/usr/bin/env bash
# Start this agent's dev server on its assigned port.
cd "$(dirname "$0")/.."
PORT="$(sed -n 's/^PORT=//p' .agent/env)"
exec npm run dev -- --port "$PORT" --strictPort
EOF
  chmod +x "$wt/.agent/dev.sh"

  # Global config has terminal.cwd=. (resolves to $HOME), which pins project-context
  # discovery away from this worktree. Pinning TERMINAL_CWD per session makes the
  # generated .hermes.md load; without it Hermes sees no project rules at all.
  cat >"$wt/.agent/hermes.sh" <<'EOF'
#!/usr/bin/env bash
# Start Hermes scoped to this worktree (loads ./.hermes.md as project context).
cd "$(dirname "$0")/.."
exec env TERMINAL_CWD="$PWD" hermes "$@"
EOF
  chmod +x "$wt/.agent/hermes.sh"

  cat >"$wt/.hermes.md" <<EOF
# Agent: \`$name\` (fabio-game-show)

You are the **$name agent**. This checkout is your own git worktree on branch
\`$(branch_of "$name")\`; other agents are editing their own worktrees of the same
repo in parallel. This file is generated by \`scripts/agents.sh setup\` — do not edit it.

## Report the URL in every message

Your dev server is **port $port**, and it is already configured:

\`\`\`bash
bash .agent/dev.sh        # Vite on port $port, strictPort (fails loudly if taken)
\`\`\`

Start any Hermes sub-session with \`bash .agent/hermes.sh\` (not a bare \`hermes\`):
the wrapper pins \`TERMINAL_CWD\` to this worktree, which is what makes this file
load as project context in the first place.

**End EVERY reply with this line, exactly:**

\`\`\`
App: $url
\`\`\`

Say it even when the change is small, and say it once more after a dev-server
restart or port change. If the server is not running, still print the line — the
human knows where to look.

## You own exactly these paths

\`\`\`
$(owns "$name")
\`\`\`

Change those and nothing else. Everything outside them belongs to another agent:

| Agent | Owns | Port |
|---|---|---|
| master | screens, components, store, types, register, index.css, App | $(port_of master) |
| board-game | src/games/boardGame/ | $(port_of board-game) |
| fighting | src/games/fighting/ | $(port_of fighting) |
| jeopardy | src/games/jeopardy/ | $(port_of jeopardy) |
| feud | src/games/feud/ | $(port_of feud) |

If your task needs a change outside your paths — a new store action, a shared
component, \`register.ts\`, \`types.ts\`, \`index.css\`, routing — do **not** make it.
Finish what you can, then report exactly what's needed and why; the human routes
it to the master agent. A same-file collision on a shared file costs more than the
feature is worth.

## Workflow

- Read the project skill (\`fabio-game-show-app\`) before editing; it carries the
  screen-lifecycle, registry and test conventions for this repo.
- Verify with \`npm run test\` and \`npm run build\` before claiming anything works.
- Commit milestones on your own branch (\`$(branch_of "$name")\`). Never commit to
  \`main\`, never merge \`main\` into your branch unless asked, never rebase a branch
  another agent is using.
- \`git status\` first and last: this repository is also edited by hand, so foreign
  untracked files and unexpected diffs are normal. Leave them alone.

## Test with your own port in mind

Screens you touch should keep passing on the shared suite. Don't start a second
Vite instance on another port, and never kill a server you didn't start.
EOF
}

cmd_setup() {
  ensure_exclude
  local targets=("$@")
  [ ${#targets[@]} -eq 0 ] && targets=("${AGENTS[@]}")
  mkdir -p "$AGENTS_DIR"
  local base
  base="$(git rev-parse --abbrev-ref HEAD)"

  if [ -n "$(git status --porcelain)" ]; then
    echo "!! This checkout has uncommitted changes. Worktrees are created from"
    echo "   '$base' ($(git rev-parse --short HEAD)), so those changes are NOT in them."
    echo "   Commit them first if the agents must see them."
    echo
  fi

  for name in "${targets[@]}"; do
    require_agent "$name"
    local wt rel
    wt="$(worktree_of "$name")"
    rel="../$(basename "$AGENTS_DIR")/$name"
    if [ ! -d "$wt" ]; then
      echo "==> creating worktree $rel on $(branch_of "$name") from $base"
      git worktree add "$rel" -b "$(branch_of "$name")" "$base"
    else
      echo "==> reusing worktree $wt"
    fi
    if [ ! -d "$wt/node_modules" ]; then
      echo "==> installing deps in $name"
      (cd "$wt" && npm ci --prefer-offline --no-audit --no-fund) || echo "   (npm ci failed — run it by hand in $wt)"
    fi
    write_agent_files "$name" "$wt"
  done
  cmd_list
}

cmd_list() {
  printf '%-12s %-6s %-22s %s\n' AGENT PORT BRANCH URL
  for name in "${AGENTS[@]}"; do
    printf '%-12s %-6s %-22s %s\n' "$name" "$(port_of "$name")" "$(branch_of "$name")" "$(app_url "$name")"
  done
  echo
  echo "worktrees: $AGENTS_DIR"
}

cmd_dev() {
  require_agent "${1:-}"
  local wt
  wt="$(worktree_of "$1")"
  [ -d "$wt" ] || { echo "no worktree for $1 — run: scripts/agents.sh setup $1" >&2; exit 1; }
  echo "==> $1 dev server: $(app_url "$1")"
  cd "$wt" && npm run dev -- --port "$(port_of "$1")" --strictPort
}

server_state() {
  local code
  # curl can exit non-zero (e.g. write error to /dev/null) while still printing
  # the status code, so keep whatever it printed and treat an empty result as down.
  code="$(curl -s -o /dev/null --max-time 1 -w '%{http_code}' "$(app_url "$1")" 2>/dev/null || true)"
  echo "${code:-000}"
}

cmd_status() {
  printf '%-12s %-6s %-8s %-10s %s\n' AGENT PORT SERVER DIRTY URL
  for name in "${AGENTS[@]}"; do
    local wt dirty
    wt="$(worktree_of "$name")"
    if [ -d "$wt" ]; then
      dirty="$(cd "$wt" && git status --porcelain | wc -l | tr -d ' ')"
    else
      dirty="no-wt"
    fi
    printf '%-12s %-6s %-8s %-10s %s\n' "$name" "$(port_of "$name")" "$(server_state "$name")" "$dirty" "$(app_url "$name")"
  done
}

cmd_urls() {
  for name in "${AGENTS[@]}"; do
    printf '%-12s %s  [%s]\n' "$name" "$(app_url "$name")" "$(server_state "$name")"
  done
}

cmd_run() {
  require_agent "${1:-}"
  local name="$1"
  shift || true
  local wt
  wt="$(worktree_of "$name")"
  [ -d "$wt" ] || { echo "no worktree for $name — run: scripts/agents.sh setup $name" >&2; exit 1; }
  cd "$wt"
  # TERMINAL_CWD pins project-context discovery to this worktree (see .agent/hermes.sh).
  if [ $# -gt 0 ]; then
    exec env TERMINAL_CWD="$PWD" hermes chat -q "$*"
  else
    exec env TERMINAL_CWD="$PWD" hermes
  fi
}

cmd_sync() {
  local targets=("$@")
  [ ${#targets[@]} -eq 0 ] && targets=("${AGENTS[@]}")
  for name in "${targets[@]}"; do
    require_agent "$name"
    local wt
    wt="$(worktree_of "$name")"
    [ -d "$wt" ] || continue
    echo "==> merging main into $(branch_of "$name")"
    (cd "$wt" && git merge main --no-edit) || echo "   conflict in $name — resolve in $wt (or spawn the merge-reconciler skill)"
  done
}

cmd_remove() {
  require_agent "${1:-}"
  local name="$1" wt
  wt="$(worktree_of "$name")"
  shift || true
  git worktree remove --force "../$(basename "$AGENTS_DIR")/$name" 2>/dev/null || rm -rf "$wt"
  if [ "${1:-}" = "--delete-branch" ]; then
    git branch -D "$(branch_of "$name")" 2>/dev/null || true
  fi
  echo "removed worktree for $name (branch $(branch_of "$name") kept unless --delete-branch)"
}

case "${1:-}" in
  setup) shift; cmd_setup "$@" ;;
  dev) shift; cmd_dev "$@" ;;
  status) cmd_status ;;
  urls) cmd_urls ;;
  run) shift; cmd_run "$@" ;;
  sync) shift; cmd_sync "$@" ;;
  remove) shift; cmd_remove "$@" ;;
  list) cmd_list ;;
  *)
    sed -n '2,14p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 1
    ;;
esac
